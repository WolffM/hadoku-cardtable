/**
 * `/api/pools/cubes` — the cube half of a draft room's pool picker: the
 * 8-cube shortlist `build-pool` generates (read-only) plus any cube a friend
 * has imported from Cube Cobra.
 *
 *   GET    /api/pools/cubes            → 200 CubeSummary[] (imported newest-first, then the shortlist)
 *   GET    /api/pools/cubes/:id/cards  → 200 DraftCard[] | 404 { error } — lane B's art preload reads a plan's cube from here, before the deal
 *   POST   /api/pools/cubes/import     { link } → 201 CubeSummary | 400 { error }
 *   POST   /api/pools/cubes/:id/refresh → 200 CubeSummary | 400 | 403 | 404
 *   DELETE /api/pools/cubes/:id        → 204 | 400 | 403 | 404
 *
 * `createCubeStore` is the in-memory index lane A's `index.ts` builds once at
 * boot and hands to `attachCubeRoutes` alongside `createForgePools`'s `check`
 * (lane D) — the wire contract both lanes write against is
 * `docs/planning/wave73-2026-10-21.md`'s "Server module contracts".
 *
 * ## Shortlist vs imported
 *
 * The shortlist's files (`shortlistDir/*.json`, shape `{ cube, size, cards }`
 * — the same shape `room/pool.ts`'s `loadPool` already reads, generated by
 * `build-pool`) are read once at construction and never written back to: they
 * are lane A's generated output, not this store's. An imported cube is a
 * snapshot plus a refresh button (the plan's ruling 4): Cube Cobra gives only
 * `name` + `scryfall_id` per card (`cubecobra.ts`), so every imported card's
 * gameplay text comes from the `CardCatalog` by name. A name the catalog does
 * not know is still counted — the card is kept with an empty `typeLine` (the
 * one field no real printing ever leaves blank), so the cube's size stays
 * accurate and `deps.check` can tell a card with no text from one Forge
 * simply does not know.
 *
 * ## Persistence
 *
 * `importDir/<id>.json` is the on-disk snapshot: `{ id, name, cubeCobraId,
 * importedBy, importedAt, refreshedAt, verdict, cards }`, written atomically
 * (temp file, then rename — the same shape `http/sounds.ts`'s header
 * documents) so a crash mid-write never leaves a half-written cube. `cards`
 * there is the trimmed Cube Cobra projection (`CubeCobraCard[]`), never the
 * derived `DraftCard[]` — the catalog can change (a resync), so gameplay text
 * is always re-derived at load, not frozen into the snapshot.
 */

import { randomUUID } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, unlinkSync } from 'node:fs';
import { mkdir, open, rename } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import express, { type NextFunction, type Request, type Response, type Router } from 'express';

import { DraftCardSchema, ImportCubeBodySchema, type CubeSummary, type DraftCard, type PoolVerdict } from '@hadoku/shared';
import { identityFromHeaders } from '../room/identity.js';
import type { CardCatalog } from './catalog.ts';
import { fetchCubeCobraCube, parseCubeCobraLink, type CubeCobraCard, type CubeCobraCube, type FetchJson } from './cubecobra.ts';

export interface CubeStore {
	list(): CubeSummary[];
	cards(id: string): readonly DraftCard[] | null;
	importLink(link: string, by: string): Promise<CubeSummary>;
	refresh(id: string, by: string): Promise<CubeSummary>;
	/** Throws a {@link CubeStoreRefusal}; never a silent no-op. */
	remove(id: string, by: string): void;
	setVerdict(id: string, verdict: PoolVerdict): void;
}

/** A typed refusal `remove`/`refresh`/`importLink` throw — the HTTP status is already decided. */
export class CubeStoreRefusal extends Error {
	readonly status: 400 | 403 | 404;
	constructor(status: 400 | 403 | 404, message: string) {
		super(message);
		this.name = 'CubeStoreRefusal';
		this.status = status;
	}
}

interface Entry {
	summary: CubeSummary;
	/** The shortlist's own resolved cards, or the imported cube's derived ones. Never persisted for imports. */
	cards: DraftCard[];
	/** Only for `origin: 'cubecobra'` — what a refresh re-derives `cards` from. */
	raw: readonly CubeCobraCard[] | null;
}

function log(entry: Record<string, unknown>): void {
	console.log(JSON.stringify({ t: new Date().toISOString(), svc: 'cardtable-pools', ...entry }));
}

interface RawShortlistFile {
	cube?: unknown;
	size?: unknown;
	cards?: unknown;
}

/** `shortlistDir/<stem>.json`, the same `{cube,size,cards}` shape `room/pool.ts`'s `loadPool` reads. */
function loadShortlistFile(path: string, id: string): { name: string; cards: DraftCard[] } | null {
	let text: string;
	try {
		text = readFileSync(path, 'utf8');
	} catch (err) {
		log({ evt: 'shortlist-load-failed', path, detail: (err as Error).message });
		return null;
	}
	let raw: RawShortlistFile;
	try {
		raw = JSON.parse(text) as RawShortlistFile;
	} catch (err) {
		log({ evt: 'shortlist-load-failed', path, detail: (err as Error).message });
		return null;
	}
	if (typeof raw.cube !== 'string' || raw.cube.length === 0 || !Array.isArray(raw.cards)) {
		log({ evt: 'shortlist-load-failed', path, detail: 'expected { cube: string, cards: [] }' });
		return null;
	}
	const cards: DraftCard[] = [];
	for (const candidate of raw.cards) {
		const parsed = DraftCardSchema.safeParse(candidate);
		if (parsed.success) cards.push(parsed.data);
	}
	if (cards.length === 0) {
		log({ evt: 'shortlist-empty', path, id });
	}
	return { name: raw.cube, cards };
}

/** A card the catalog has no text for: kept (the cube's size stays true), typeLine empty on purpose — see the file header. */
function missingTextCard(name: string, scryfallId: string | null, cardId: string): DraftCard {
	return {
		cardId,
		...(scryfallId !== null ? { scryfallId } : {}),
		name,
		manaCost: [],
		manaValue: 0,
		colors: [],
		typeLine: '',
		oracleText: '',
		setCode: '???',
		collectorNumber: '0',
		rarity: 'special',
	} as DraftCard;
}

const SCRYFALL_UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Project the catalog's gameplay text (or the missing-text stand-in) onto an imported cube's raw names, with fresh per-copy ids. */
function deriveImportedCards(id: string, raw: readonly CubeCobraCard[], catalog: CardCatalog): DraftCard[] {
	return raw.map((card, i) => {
		const cardId = `${id}-${i}`;
		const resolved = catalog.byName(card.name);
		if (resolved !== null) return { ...resolved, cardId };
		const scryfallId = card.scryfallId !== null && SCRYFALL_UUID_RE.test(card.scryfallId) ? card.scryfallId : null;
		return missingTextCard(card.name, scryfallId, cardId);
	});
}

interface ImportFile {
	id: string;
	name: string;
	cubeCobraId: string;
	importedBy: string;
	importedAt: string;
	refreshedAt: string | null;
	verdict: PoolVerdict | null;
	cards: CubeCobraCard[];
}

function isCubeCobraCard(value: unknown): value is CubeCobraCard {
	if (typeof value !== 'object' || value === null) return false;
	const v = value as Record<string, unknown>;
	return typeof v.name === 'string' && (v.scryfallId === null || typeof v.scryfallId === 'string');
}

function parseImportFile(text: string, path: string): ImportFile | null {
	let raw: unknown;
	try {
		raw = JSON.parse(text);
	} catch (err) {
		log({ evt: 'import-load-failed', path, detail: (err as Error).message });
		return null;
	}
	if (typeof raw !== 'object' || raw === null) return null;
	const v = raw as Record<string, unknown>;
	if (
		typeof v.id !== 'string' ||
		typeof v.name !== 'string' ||
		typeof v.cubeCobraId !== 'string' ||
		typeof v.importedBy !== 'string' ||
		typeof v.importedAt !== 'string' ||
		!Array.isArray(v.cards)
	) {
		log({ evt: 'import-load-failed', path, detail: 'malformed import file' });
		return null;
	}
	const cards = v.cards.filter(isCubeCobraCard);
	return {
		id: v.id,
		name: v.name,
		cubeCobraId: v.cubeCobraId,
		importedBy: v.importedBy,
		importedAt: v.importedAt,
		refreshedAt: typeof v.refreshedAt === 'string' ? v.refreshedAt : null,
		verdict: (v.verdict as PoolVerdict | null | undefined) ?? null,
		cards,
	};
}

/** Temp file, then rename over the target — never a half-written cube survives a crash. */
async function writeAtomic(target: string, data: unknown): Promise<void> {
	await mkdir(dirname(target), { recursive: true });
	const tmp = `${target}.${process.pid}.${randomUUID()}.tmp`;
	const handle = await open(tmp, 'w');
	try {
		await handle.writeFile(JSON.stringify(data, null, 2));
	} finally {
		await handle.close();
	}
	await rename(tmp, target);
}

export interface CreateCubeStoreOpts {
	shortlistDir: string;
	importDir: string;
	catalog: CardCatalog;
	/** Injectable; default global `fetch`. Passed straight through to {@link fetchCubeCobraCube}. */
	fetchJson?: FetchJson;
}

export function createCubeStore(opts: CreateCubeStoreOpts): CubeStore {
	const { shortlistDir, importDir, catalog } = opts;
	const fetchCube = (id: string): Promise<CubeCobraCube> => fetchCubeCobraCube(id, opts.fetchJson);

	const shortlist = new Map<string, Entry>();
	const shortlistOrder: string[] = [];
	try {
		const files = readdirSync(shortlistDir)
			.filter((f) => f.endsWith('.json'))
			.sort();
		for (const file of files) {
			const id = file.slice(0, -'.json'.length);
			const loaded = loadShortlistFile(join(shortlistDir, file), id);
			if (loaded === null) continue;
			shortlistOrder.push(id);
			shortlist.set(id, {
				cards: loaded.cards,
				raw: null,
				summary: {
					id,
					name: loaded.name,
					size: loaded.cards.length,
					origin: 'shortlist',
					cubeCobraId: null,
					importedBy: null,
					importedAt: null,
					refreshedAt: null,
					verdict: null,
				},
			});
		}
	} catch (err) {
		log({ evt: 'shortlist-dir-missing', shortlistDir, detail: (err as Error).message });
	}

	const imported = new Map<string, Entry>();
	try {
		mkdirSync(importDir, { recursive: true });
		const files = readdirSync(importDir).filter((f) => f.endsWith('.json'));
		for (const file of files) {
			let text: string;
			try {
				text = readFileSync(join(importDir, file), 'utf8');
			} catch (err) {
				log({ evt: 'import-load-failed', file, detail: (err as Error).message });
				continue;
			}
			const parsed = parseImportFile(text, join(importDir, file));
			if (parsed === null) continue;
			const cards = deriveImportedCards(parsed.id, parsed.cards, catalog);
			imported.set(parsed.id, {
				raw: parsed.cards,
				cards,
				summary: {
					id: parsed.id,
					name: parsed.name,
					size: cards.length,
					origin: 'cubecobra',
					cubeCobraId: parsed.cubeCobraId,
					importedBy: parsed.importedBy,
					importedAt: parsed.importedAt,
					refreshedAt: parsed.refreshedAt,
					verdict: parsed.verdict,
				},
			});
		}
	} catch (err) {
		log({ evt: 'import-dir-missing', importDir, detail: (err as Error).message });
	}

	const entryOf = (id: string): Entry | null => imported.get(id) ?? shortlist.get(id) ?? null;

	const importFilePath = (id: string): string => join(importDir, `${id}.json`);

	const persistImport = async (entry: Entry): Promise<void> => {
		const s = entry.summary;
		const file: ImportFile = {
			id: s.id,
			name: s.name,
			cubeCobraId: s.cubeCobraId ?? '',
			importedBy: s.importedBy ?? '',
			importedAt: s.importedAt ?? new Date().toISOString(),
			refreshedAt: s.refreshedAt,
			verdict: s.verdict,
			cards: [...(entry.raw ?? [])],
		};
		await writeAtomic(importFilePath(s.id), file);
	};

	return {
		list(): CubeSummary[] {
			const importedSorted = [...imported.values()]
				.sort((a, b) => (b.summary.importedAt ?? '').localeCompare(a.summary.importedAt ?? ''))
				.map((e) => e.summary);
			const shortlisted = shortlistOrder.flatMap((id) => {
				const entry = shortlist.get(id);
				return entry === undefined ? [] : [entry.summary];
			});
			return [...importedSorted, ...shortlisted];
		},

		cards(id: string): readonly DraftCard[] | null {
			const entry = entryOf(id);
			return entry === null ? null : entry.cards;
		},

		async importLink(link: string, by: string): Promise<CubeSummary> {
			const parsedLink = parseCubeCobraLink(link);
			if (!parsedLink.ok) throw new CubeStoreRefusal(400, parsedLink.error);
			let cube: Awaited<ReturnType<typeof fetchCube>>;
			try {
				cube = await fetchCube(parsedLink.id);
			} catch (err) {
				throw new CubeStoreRefusal(400, `could not import ${JSON.stringify(link)}: ${(err as Error).message}`);
			}
			const id = `cc-${parsedLink.id}`;
			const now = new Date().toISOString();
			const cards = deriveImportedCards(id, cube.cards, catalog);
			const entry: Entry = {
				raw: cube.cards,
				cards,
				summary: {
					id,
					name: cube.name,
					size: cards.length,
					origin: 'cubecobra',
					cubeCobraId: parsedLink.id,
					importedBy: by,
					importedAt: now,
					refreshedAt: null,
					verdict: null,
				},
			};
			imported.set(id, entry);
			await persistImport(entry);
			return entry.summary;
		},

		// `by` is unused on purpose: refresh is any friend's, not only the importer's (ruling 4).
		// Kept in the signature for parity with `remove`/`importLink`, both of which need it.
		async refresh(id: string, _by: string): Promise<CubeSummary> {
			const entry = imported.get(id);
			if (entry === undefined) {
				if (shortlist.has(id)) throw new CubeStoreRefusal(400, 'a shortlist cube cannot be refreshed');
				throw new CubeStoreRefusal(404, `no imported cube ${JSON.stringify(id)}`);
			}
			const cubeCobraId = entry.summary.cubeCobraId;
			if (cubeCobraId === null) throw new CubeStoreRefusal(400, 'cube has no Cube Cobra id to refresh from');
			let cube: Awaited<ReturnType<typeof fetchCube>>;
			try {
				cube = await fetchCube(cubeCobraId);
			} catch (err) {
				throw new CubeStoreRefusal(400, `could not refresh: ${(err as Error).message}`);
			}
			const cards = deriveImportedCards(id, cube.cards, catalog);
			entry.raw = cube.cards;
			entry.cards = cards;
			entry.summary = {
				...entry.summary,
				name: cube.name,
				size: cards.length,
				refreshedAt: new Date().toISOString(),
				verdict: null,
			};
			await persistImport(entry);
			return entry.summary;
		},

		remove(id: string, by: string): void {
			if (shortlist.has(id)) throw new CubeStoreRefusal(400, 'a shortlist cube cannot be deleted');
			const entry = imported.get(id);
			if (entry === undefined) throw new CubeStoreRefusal(404, `no imported cube ${JSON.stringify(id)}`);
			if (entry.summary.importedBy !== by) throw new CubeStoreRefusal(403, 'only the importer may delete this cube');
			imported.delete(id);
			try {
				unlinkSync(importFilePath(id));
			} catch (err) {
				log({ evt: 'import-delete-failed', id, detail: (err as Error).message });
			}
		},

		setVerdict(id: string, verdict: PoolVerdict): void {
			const entry = entryOf(id);
			if (entry === null) return;
			entry.summary = { ...entry.summary, verdict };
			if (imported.has(id)) {
				persistImport(entry).catch((err: unknown) => log({ evt: 'verdict-persist-failed', id, detail: (err as Error).message }));
			}
		},
	};
}

function badRequest(res: Response, error: string): void {
	res.status(400).json({ error });
}

function refusalStatus(res: Response, err: unknown): void {
	if (err instanceof CubeStoreRefusal) {
		res.status(err.status).json({ error: err.message });
		return;
	}
	throw err;
}

export interface AttachCubeRoutesDeps {
	store: CubeStore;
	check: (cards: readonly DraftCard[]) => Promise<PoolVerdict>;
	log?: (entry: Record<string, unknown>) => void;
}

/**
 * Mounted by lane A's `index.ts` on the `api` router, the way `http/decks.ts`'s
 * `attachDecks` is. A cube's verdict is (re-)computed and saved right here,
 * at import and at refresh — "An import is checked when it is saved" (the
 * plan's Design) — not only when a room selects it.
 */
export function attachCubeRoutes(api: Router, deps: AttachCubeRoutesDeps): void {
	const { store, check } = deps;
	const warn = deps.log ?? ((entry) => console.log(JSON.stringify({ t: new Date().toISOString(), svc: 'cardtable-pools', ...entry })));
	const cubes = express.Router();
	cubes.use(express.json({ limit: '4kb' }));

	const callerOf = (req: Request): string => identityFromHeaders(req.headers, `http-${randomUUID()}`);

	const checkAndSave = async (summary: CubeSummary): Promise<CubeSummary> => {
		const cards = store.cards(summary.id);
		if (cards === null) return summary;
		try {
			const verdict = await check(cards);
			store.setVerdict(summary.id, verdict);
			return { ...summary, verdict };
		} catch (err) {
			warn({ evt: 'cube-verdict-failed', id: summary.id, detail: (err as Error).message });
			return summary;
		}
	};

	cubes.get('/', (_req: Request, res: Response) => {
		res.json(store.list());
	});

	cubes.get('/:id/cards', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const cards = store.cards(id);
		if (cards === null) {
			res.status(404).json({ error: `no cube ${JSON.stringify(id)}` });
			return;
		}
		res.json(cards);
	});

	cubes.post('/import', (req: Request, res: Response) => {
		const parsed = ImportCubeBodySchema.safeParse(req.body);
		if (!parsed.success) return badRequest(res, 'body is { link }, 1 to 300 characters');
		const caller = callerOf(req);
		store
			.importLink(parsed.data.link, caller)
			.then((summary) => checkAndSave(summary))
			.then((summary) => res.status(201).json(summary))
			.catch((err: unknown) => {
				try {
					refusalStatus(res, err);
				} catch {
					warn({ evt: 'cube-import-failed', detail: (err as Error).message });
					badRequest(res, (err as Error).message);
				}
			});
	});

	cubes.post('/:id/refresh', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const caller = callerOf(req);
		store
			.refresh(id, caller)
			.then((summary) => checkAndSave(summary))
			.then((summary) => res.json(summary))
			.catch((err: unknown) => {
				try {
					refusalStatus(res, err);
				} catch {
					warn({ evt: 'cube-refresh-failed', id, detail: (err as Error).message });
					badRequest(res, (err as Error).message);
				}
			});
	});

	cubes.delete('/:id', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const caller = callerOf(req);
		try {
			store.remove(id, caller);
			res.status(204).end();
		} catch (err) {
			refusalStatus(res, err);
		}
	});

	api.use('/pools/cubes', cubes);
	// `express.json()`'s parse failure, same shape as `http/decks.ts`'s handler.
	api.use('/pools/cubes', (err: unknown, _req: Request, res: Response, next: NextFunction) => {
		if (res.headersSent) return next(err);
		const e = err as { type?: unknown; status?: unknown };
		if (e.type === 'entity.parse.failed' || (typeof e.status === 'number' && e.status >= 400 && e.status < 500)) {
			res.status(400).json({ error: 'the request body could not be read' });
			return;
		}
		next(err);
	});
}
