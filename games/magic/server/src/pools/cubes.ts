export interface CubeStore {
	list(): CubeSummary[];
	cards(id: string): readonly DraftCard[] | null;
	importLink(link: string, by: string, userId?: string | null): Promise<CubeSummary>;
	/** A pasted card list, saved under `name`. Every paste is a new cube: a list has no id of its own to import again. */
	importList(name: string, list: string, by: string, userId?: string | null): Promise<CubeSummary>;
	/** The importer's account, or `null`: the shortlist, an erased importer, or an import that never kept one. */
	importerUser(id: string): string | null;
	/** Keep `userId` as the account behind an import that has none. A no-op for any other cube. */
	claim(id: string, userId: string): void;
	refresh(id: string, by: string): Promise<CubeSummary>;
	/** Throws a {@link CubeStoreRefusal}; never a silent no-op. */
	remove(id: string, by: string): void;
	setVerdict(id: string, verdict: PoolVerdict): void;
	/** Account erase: cubes imported by one of `ids` are credited to `to`. Answers how many, once saved. */
	anonymise(ids: ReadonlySet<string>, to: string): Promise<number>;
	/**
	 * Account merge: cubes the merged-away account imported are the kept account's, by participant id
	 * and by account (`renames`: old id → new). Answers how many, once saved.
	 */
	merge(renames: ReadonlyMap<string, string>): Promise<number>;
}

/** A typed refusal `remove`/`refresh`/`importLink`/`importList` throw — the HTTP status is already decided. */
export class CubeStoreRefusal extends Error {
	readonly status: 400 | 403 | 404;
	constructor(status: 400 | 403 | 404, message: string) {
		super(message);
		this.name = 'CubeStoreRefusal';
		this.status = status;
	}
}

interface Entry {
	summary: CubeSummary;
	/** The shortlist's own resolved cards, or the imported cube's derived ones. Never persisted for imports; replaced, never edited. */
	cards: readonly DraftCard[];
	/** The importer's account. Beside the summary, never in it: the wire carries a name, not an account. */
	user: string | null;
	/** Every imported cube's own names — what a catalog change or a refresh re-derives `cards` from. `null` for the shortlist. */
	raw: readonly CubeCobraCard[] | null;
}

const log = jsonLogger('cardtable-pools');

interface RawShortlistFile {
	cube?: unknown;
	size?: unknown;
	cards?: unknown;
}

/** `shortlistDir/<stem>.json`, the same `{cube,size,cards}` shape `room/pool.ts`'s `loadPool` reads. */
function loadShortlistFile(path: string, id: string): { name: string; cards: DraftCard[] } | null {
	let text: string;
	try {
		text = readFileSync(path, 'utf8');
	} catch (err) {
		log({ evt: 'shortlist-load-failed', path, detail: (err as Error).message });
		return null;
	}
	let raw: RawShortlistFile;
	try {
		raw = JSON.parse(text) as RawShortlistFile;
	} catch (err) {
		log({ evt: 'shortlist-load-failed', path, detail: (err as Error).message });
		return null;
	}
	if (typeof raw.cube !== 'string' || raw.cube.length === 0 || !Array.isArray(raw.cards)) {
		log({ evt: 'shortlist-load-failed', path, detail: 'expected { cube: string, cards: [] }' });
		return null;
	}
	const cards: DraftCard[] = [];
	for (const candidate of raw.cards) {
		const parsed = DraftCardSchema.safeParse(candidate);
		if (parsed.success) cards.push(parsed.data);
	}
	if (cards.length === 0) {
		log({ evt: 'shortlist-empty', path, id });
	}
	return { name: raw.cube, cards };
}

/**
 * `pools/cube-art.json` — a committed `cubeId → card NAME` map for the
 * shortlist (AF305 §B, the room's cube gallery). One pick per cube, repointed
 * by editing this file; never an image or a URL. Read once at construction,
 * beside `shortlistDir` (its sibling, not inside it) — missing or malformed
 * is logged and treated as empty, the same tolerance every other file this
 * store reads already has.
 */
function loadCubeArtNames(path: string): Readonly<Record<string, string>> {
	let text: string;
	try {
		text = readFileSync(path, 'utf8');
	} catch (err) {
		log({ evt: 'cube-art-missing', path, detail: (err as Error).message });
		return {};
	}
	let raw: unknown;
	try {
		raw = JSON.parse(text);
	} catch (err) {
		log({ evt: 'cube-art-invalid', path, detail: (err as Error).message });
		return {};
	}
	if (typeof raw !== 'object' || raw === null) return {};
	const out: Record<string, string> = {};
	for (const [id, name] of Object.entries(raw as Record<string, unknown>)) {
		if (typeof name === 'string' && name.length > 0) out[id] = name;
	}
	return out;
}

/** The named card's own `scryfallId` among `cards`, or `null` — never invented, never a second lookup. */
function artIdOf(cards: readonly DraftCard[], name: string | undefined): string | null {
	if (name === undefined) return null;
	const card = cards.find((c) => c.name === name);
	return card?.scryfallId ?? null;
}

/** A card the catalog has no text for: kept (the cube's size stays true), typeLine empty on purpose — see the file header. */
function missingTextCard(name: string, scryfallId: string | null, cardId: string): DraftCard {
	return {
		cardId,
		...(scryfallId !== null ? { scryfallId } : {}),
		name,
		manaCost: [],
		manaValue: 0,
		colors: [],
		typeLine: '',
		oracleText: '',
		setCode: '???',
		collectorNumber: '0',
		rarity: 'special',
	} as DraftCard;
}

const SCRYFALL_UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Project the catalog's gameplay text (or the missing-text stand-in) onto an imported cube's raw names, with fresh per-copy ids. */
function deriveImportedCards(id: string, raw: readonly CubeCobraCard[], catalog: CardCatalog): DraftCard[] {
	// No Alchemy (the operator, 2026-11-01): an Arena cube's Alchemy and "A-" cards are left out.
	return raw.flatMap((card, i) => {
		if (catalog.isAlchemy(card.name)) return [];
		const cardId = `${id}-${i}`;
		const resolved = catalog.byName(card.name);
		if (resolved !== null) return [{ ...resolved, cardId }];
		const scryfallId = card.scryfallId !== null && SCRYFALL_UUID_RE.test(card.scryfallId) ? card.scryfallId : null;
		return [missingTextCard(card.name, scryfallId, cardId)];
	});
}

interface ImportFile {
	id: string;
	name: string;
	/** `null` for a pasted list. */
	cubeCobraId: string | null;
	importedBy: string;
	/** `null` for a file persisted before the account was kept, and once its importer is erased. */
	importedByUser: string | null;
	importedAt: string;
	refreshedAt: string | null;
	verdict: PoolVerdict | null;
	cards: CubeCobraCard[];
	/** `null` for a file persisted before AF305 §B — read back as "no art yet", not a crash; the next refresh fills it in. */
	artId: string | null;
}

function isCubeCobraCard(value: unknown): value is CubeCobraCard {
	if (typeof value !== 'object' || value === null) return false;
	const v = value as Record<string, unknown>;
	return typeof v.name === 'string' && (v.scryfallId === null || typeof v.scryfallId === 'string');
}

function parseImportFile(text: string, path: string): ImportFile | null {
	let raw: unknown;
	try {
		raw = JSON.parse(text);
	} catch (err) {
		log({ evt: 'import-load-failed', path, detail: (err as Error).message });
		return null;
	}
	if (typeof raw !== 'object' || raw === null) return null;
	const v = raw as Record<string, unknown>;
	if (
		typeof v.id !== 'string' ||
		typeof v.name !== 'string' ||
		(v.cubeCobraId !== null && typeof v.cubeCobraId !== 'string') ||
		typeof v.importedBy !== 'string' ||
		typeof v.importedAt !== 'string' ||
		!Array.isArray(v.cards)
	) {
		log({ evt: 'import-load-failed', path, detail: 'malformed import file' });
		return null;
	}
	const cards = v.cards.filter(isCubeCobraCard);
	return {
		id: v.id,
		name: v.name,
		cubeCobraId: v.cubeCobraId,
		importedBy: v.importedBy,
		importedByUser: typeof v.importedByUser === 'string' ? v.importedByUser : null,
		importedAt: v.importedAt,
		refreshedAt: typeof v.refreshedAt === 'string' ? v.refreshedAt : null,
		verdict: (v.verdict as PoolVerdict | null | undefined) ?? null,
		cards,
		artId: typeof v.artId === 'string' ? v.artId : null,
	};
}

/** Temp file, then rename over the target — never a half-written cube survives a crash. */
async function writeAtomic(target: string, data: unknown): Promise<void> {
	await mkdir(dirname(target), { recursive: true });
	const tmp = `${target}.${process.pid}.${randomUUID()}.tmp`;
	const handle = await open(tmp, 'w');
	try {
		await handle.writeFile(JSON.stringify(data, null, 2));
	} finally {
		await handle.close();
	}
	await rename(tmp, target);
}

export interface CreateCubeStoreOpts {
	shortlistDir: string;
	importDir: string;
	catalog: CardCatalog;
	/** Injectable; default global `fetch`. Passed straight through to {@link fetchCubeCobraCube}. */
	fetchJson?: FetchJson;
	/** Where Cube Cobra is. Default the real one; an e2e stack points it at its own stand-in. */
	cubeCobraOrigin?: string;
	/**
	 * `pools/cube-art.json`'s path — the shortlist's own `cubeId → card name`
	 * art map (AF305 §B). Defaults to `shortlistDir`'s SIBLING (`shortlistDir`
	 * is `pools/cubes`; this is `pools/cube-art.json`), which is where the
	 * real one is committed, so production wires nothing new. Injectable for
	 * a test that does not want to lay out that exact directory shape.
	 */
	cubeArtPath?: string;
}

export function createCubeStore(opts: CreateCubeStoreOpts): CubeStore {
	const { shortlistDir, importDir, catalog } = opts;
	const fetchCube = (id: string): Promise<CubeCobraCube> => fetchCubeCobraCube(id, opts.fetchJson, opts.cubeCobraOrigin);
	const cubeArtNames = loadCubeArtNames(opts.cubeArtPath ?? join(dirname(shortlistDir), 'cube-art.json'));

	const shortlist = new Map<string, Entry>();
	const shortlistOrder: string[] = [];
	try {
		const files = readdirSync(shortlistDir)
			.filter((f) => f.endsWith('.json'))
			.sort();
		for (const file of files) {
			const id = file.slice(0, -'.json'.length);
			const loaded = loadShortlistFile(join(shortlistDir, file), id);
			if (loaded === null) continue;
			shortlistOrder.push(id);
			shortlist.set(id, {
				cards: loaded.cards,
				user: null,
				raw: null,
				summary: {
					id,
					name: loaded.name,
					size: loaded.cards.length,
					origin: 'shortlist',
					cubeCobraId: null,
					importedBy: null,
					importedAt: null,
					refreshedAt: null,
					verdict: null,
					artId: artIdOf(loaded.cards, cubeArtNames[id]),
				},
			});
		}
	} catch (err) {
		log({ evt: 'shortlist-dir-missing', shortlistDir, detail: (err as Error).message });
	}

	const imported = new Map<string, Entry>();
	try {
		mkdirSync(importDir, { recursive: true });
		const files = readdirSync(importDir).filter((f) => f.endsWith('.json'));
		for (const file of files) {
			let text: string;
			try {
				text = readFileSync(join(importDir, file), 'utf8');
			} catch (err) {
				log({ evt: 'import-load-failed', file, detail: (err as Error).message });
				continue;
			}
			const parsed = parseImportFile(text, join(importDir, file));
			if (parsed === null) continue;
			const cards = deriveImportedCards(parsed.id, parsed.cards, catalog);
			imported.set(parsed.id, {
				user: parsed.importedByUser,
				raw: parsed.cards,
				cards,
				summary: {
					id: parsed.id,
					name: parsed.name,
					size: cards.length,
					origin: parsed.cubeCobraId === null ? 'list' : 'cubecobra',
					cubeCobraId: parsed.cubeCobraId,
					importedBy: parsed.importedBy,
					importedAt: parsed.importedAt,
					refreshedAt: parsed.refreshedAt,
					verdict: parsed.verdict,
					artId: parsed.artId,
				},
			});
		}
	} catch (err) {
		log({ evt: 'import-dir-missing', importDir, detail: (err as Error).message });
	}

	const entryOf = (id: string): Entry | null => imported.get(id) ?? shortlist.get(id) ?? null;

	const importFilePath = (id: string): string => join(importDir, `${id}.json`);

	const persistImport = async (entry: Entry): Promise<void> => {
		const s = entry.summary;
		const file: ImportFile = {
			id: s.id,
			name: s.name,
			cubeCobraId: s.cubeCobraId,
			importedBy: s.importedBy ?? '',
			importedByUser: entry.user,
			importedAt: s.importedAt ?? new Date().toISOString(),
			refreshedAt: s.refreshedAt,
			verdict: s.verdict,
			cards: [...(entry.raw ?? [])],
			artId: s.artId,
		};
		await writeAtomic(importFilePath(s.id), file);
	};

	return {
		list(): CubeSummary[] {
			const importedSorted = [...imported.values()]
				.sort((a, b) => (b.summary.importedAt ?? '').localeCompare(a.summary.importedAt ?? ''))
				.map((e) => e.summary);
			const shortlisted = shortlistOrder.flatMap((id) => {
				const entry = shortlist.get(id);
				return entry === undefined ? [] : [entry.summary];
			});
			return [...importedSorted, ...shortlisted];
		},

		cards(id: string): readonly DraftCard[] | null {
			const entry = entryOf(id);
			return entry === null ? null : entry.cards;
		},

		async importLink(link: string, by: string, userId: string | null = null): Promise<CubeSummary> {
			const parsedLink = parseCubeCobraLink(link);
			if (!parsedLink.ok) throw new CubeStoreRefusal(400, parsedLink.error);
			let cube: Awaited<ReturnType<typeof fetchCube>>;
			try {
				cube = await fetchCube(parsedLink.id);
			} catch (err) {
				throw new CubeStoreRefusal(400, `could not import ${JSON.stringify(link)}: ${(err as Error).message}`);
			}
			const id = `cc-${parsedLink.id}`;
			const now = new Date().toISOString();
			const cards = deriveImportedCards(id, cube.cards, catalog);
			const entry: Entry = {
				user: userId,
				raw: cube.cards,
				cards,
				summary: {
					id,
					name: cube.name,
					size: cards.length,
					origin: 'cubecobra',
					cubeCobraId: parsedLink.id,
					importedBy: by,
					importedAt: now,
					refreshedAt: null,
					verdict: null,
					artId: cube.artId,
				},
			};
			imported.set(id, entry);
			await persistImport(entry);
			return entry.summary;
		},

		async importList(name: string, list: string, by: string, userId: string | null = null): Promise<CubeSummary> {
			const parsed = parseCubeList(list);
			if (!parsed.ok) throw new CubeStoreRefusal(400, parsed.error);
			const id = `list-${randomUUID().slice(0, 8)}`;
			// MTGO writes a split card `Life/Death`; the catalog's name for it is `Life // Death`.
			const spelled = (cardName: string): string => {
				const split = cardName.replace(/\s*\/+\s*/g, ' // ');
				return split !== cardName && catalog.byName(cardName) === null && catalog.byName(split) !== null ? split : cardName;
			};
			const raw: CubeCobraCard[] = parsed.names.map((cardName) => ({ name: spelled(cardName), scryfallId: null }));
			const cards = deriveImportedCards(id, raw, catalog);
			const entry: Entry = {
				user: userId,
				raw,
				cards,
				summary: {
					id,
					name,
					size: cards.length,
					origin: 'list',
					cubeCobraId: null,
					importedBy: by,
					importedAt: new Date().toISOString(),
					refreshedAt: null,
					verdict: null,
					artId: cards.find((c) => c.scryfallId !== undefined && SCRYFALL_UUID_RE.test(c.scryfallId))?.scryfallId ?? null,
				},
			};
			imported.set(id, entry);
			await persistImport(entry);
			return entry.summary;
		},

		// `by` is unused on purpose: refresh is any friend's, not only the importer's (ruling 4).
		// Kept in the signature for parity with `remove`/`importLink`, both of which need it.
		async refresh(id: string, _by: string): Promise<CubeSummary> {
			const entry = imported.get(id);
			if (entry === undefined) {
				if (shortlist.has(id)) throw new CubeStoreRefusal(400, 'a shortlist cube cannot be refreshed');
				throw new CubeStoreRefusal(404, `no imported cube ${JSON.stringify(id)}`);
			}
			const cubeCobraId = entry.summary.cubeCobraId;
			if (cubeCobraId === null) throw new CubeStoreRefusal(400, 'a pasted list has nothing to refresh from');
			let cube: Awaited<ReturnType<typeof fetchCube>>;
			try {
				cube = await fetchCube(cubeCobraId);
			} catch (err) {
				throw new CubeStoreRefusal(400, `could not refresh: ${(err as Error).message}`);
			}
			const cards = deriveImportedCards(id, cube.cards, catalog);
			entry.raw = cube.cards;
			entry.cards = cards;
			entry.summary = {
				...entry.summary,
				name: cube.name,
				size: cards.length,
				refreshedAt: new Date().toISOString(),
				verdict: null,
				artId: cube.artId,
			};
			await persistImport(entry);
			return entry.summary;
		},

		remove(id: string, by: string): void {
			if (shortlist.has(id)) throw new CubeStoreRefusal(400, 'a shortlist cube cannot be deleted');
			const entry = imported.get(id);
			if (entry === undefined) throw new CubeStoreRefusal(404, `no imported cube ${JSON.stringify(id)}`);
			if (entry.summary.importedBy !== by) throw new CubeStoreRefusal(403, 'only the importer may delete this cube');
			imported.delete(id);
			try {
				unlinkSync(importFilePath(id));
			} catch (err) {
				log({ evt: 'import-delete-failed', id, detail: (err as Error).message });
			}
		},

		async anonymise(ids: ReadonlySet<string>, to: string): Promise<number> {
			const theirs = [...imported.values()].filter((e) => e.summary.importedBy !== null && ids.has(e.summary.importedBy));
			for (const entry of theirs) {
				entry.user = null;
				entry.summary = { ...entry.summary, importedBy: to };
				await persistImport(entry);
			}
			return theirs.length;
		},

		async merge(renames: ReadonlyMap<string, string>): Promise<number> {
			// An import is its importer's own record: nothing in it can name the kept account too, so nothing conflicts.
			let moved = 0;
			for (const entry of imported.values()) {
				const importedBy = entry.summary.importedBy === null ? undefined : renames.get(entry.summary.importedBy);
				if (importedBy === undefined) continue;
				if (entry.user !== null) entry.user = renames.get(entry.user) ?? entry.user;
				entry.summary = { ...entry.summary, importedBy };
				await persistImport(entry);
				moved++;
			}
			return moved;
		},

		importerUser(id: string): string | null {
			return imported.get(id)?.user ?? null;
		},

		claim(id: string, userId: string): void {
			const entry = imported.get(id);
			if (entry === undefined || entry.user !== null) return;
			entry.user = userId;
			persistImport(entry).catch((err: unknown) => log({ evt: 'claim-persist-failed', id, detail: (err as Error).message }));
		},

		setVerdict(id: string, verdict: PoolVerdict): void {
			const entry = entryOf(id);
			if (entry === null) return;
			entry.summary = { ...entry.summary, verdict };
			if (imported.has(id)) {
				persistImport(entry).catch((err: unknown) => log({ evt: 'verdict-persist-failed', id, detail: (err as Error).message }));
			}
		},
	};
}

function badRequest(res: Response, error: string): void {
	res.status(400).json({ error });
}

function refusalStatus(res: Response, err: unknown): void {
	if (err instanceof CubeStoreRefusal) {
		res.status(err.status).json({ error: err.message });
		return;
	}
	throw err;
}

export interface AttachCubeRoutesDeps {
	store: CubeStore;
	/** Names an importer from their account, as it is now. */
	people: Pick<People, 'resolve'>;
	check: (cards: readonly DraftCard[]) => Promise<PoolVerdict>;
	/** Drafts and matches played from each cube, joined onto the listing. Absent: the listing carries no `usage`. */
	usage?: PoolUsageSource;
	log?: (entry: Record<string, unknown>) => void;
	/** Overrides {@link CUBE_IMPORT_RATE_LIMIT}; `null` is none (`perCallerLimit`). */
	importRateLimit?: RateLimitConfig | null;
}

/** A burst of 10 imports, then one every 30 seconds: each is a fetch or a parse, a Forge check and a file. */
export const CUBE_IMPORT_RATE_LIMIT: RateLimitConfig = { capacity: 10, refillAmount: 1, refillIntervalMs: 30_000 };

/**
 * Mounted by lane A's `index.ts` on the `api` router, the way `http/decks.ts`'s
 * `attachDecks` is. A cube's verdict is (re-)computed and saved right here,
 * at import and at refresh — "An import is checked when it is saved" (the
 * plan's Design) — not only when a room selects it.
 */
export function attachCubeRoutes(api: Router, deps: AttachCubeRoutesDeps): void {
	const { store, check, people } = deps;
	const warn = deps.log ?? log;
	const cubes = express.Router();
	// A pasted list is the one large body here: `CUBE_LIST_MAX_CHARS` of names, and JSON's own escaping.
	cubes.use(express.json({ limit: '512kb' }));
	const importLimit = perCallerLimit(deps.importRateLimit === undefined ? CUBE_IMPORT_RATE_LIMIT : deps.importRateLimit, 'too many imports; wait a little and try again', {
		act: 'cube-import',
		onRefused: () => warn({ evt: 'cube-import-limited' }),
	});

	const checkAndSave = async (summary: CubeSummary): Promise<CubeSummary> => {
		const cards = store.cards(summary.id);
		if (cards === null) return summary;
		try {
			const verdict = await check(cards);
			store.setVerdict(summary.id, verdict);
			return { ...summary, verdict };
		} catch (err) {
			warn({ evt: 'cube-verdict-failed', id: summary.id, detail: (err as Error).message });
			return summary;
		}
	};

	/** Each cube as this caller is shown it. A lookup that fails names nobody; the list is still the list. */
	const shown = async (req: Request, summaries: readonly CubeSummary[]): Promise<CubeListing[]> => {
		const caller = httpCaller(req);
		const account = accountIdOf(req);
		for (const s of summaries) if (account !== null && s.importedBy === caller) store.claim(s.id, account);
		const users = summaries.flatMap((s) => store.importerUser(s.id) ?? []);
		const found = users.length === 0 ? new Map<string, { name: string | null }>() : await people.resolve(users, { within: SCREEN_WAIT_MS }).catch(() => new Map<string, { name: string | null }>());
		return summaries.map((s) => {
			const user = store.importerUser(s.id);
			return { ...s, importerName: (user === null ? undefined : found.get(user)?.name) ?? null, mine: s.importedBy === caller };
		});
	};

	cubes.get('/', (req: Request, res: Response, next) => {
		Promise.all([shown(req, store.list()), deps.usage?.usage() ?? null]).then(
			([list, usage]) => res.json(usage === null ? list : joinUsage(list, (c) => cubePoolKey(c.id), usage)),
			next,
		);
	});

	// A cube's card list (the vintage cube's is 244 KB) is serialized once per version of it. Keyed by
	// the store's own array, which an import or a refresh replaces and nothing edits: a changed cube is
	// a new key, and a deleted one is never asked for again.
	const cardsAnswers = new WeakMap<readonly DraftCard[], PreparedJson>();
	cubes.get('/:id/cards', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const cards = store.cards(id);
		if (cards === null) {
			res.status(404).json({ error: `no cube ${JSON.stringify(id)}` });
			return;
		}
		let answer = cardsAnswers.get(cards);
		if (answer === undefined) cardsAnswers.set(cards, (answer = prepareJson(cards, 'cube')));
		sendPrepared(res, answer);
	});

	// The lobby's cube spotlight shows three of a cube's cards. It used to fetch the whole card list
	// (the vintage cube's is 244 KB) on every visit to draw them itself.
	cubes.get('/:id/arts', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const cards = store.cards(id);
		if (cards === null) {
			res.status(404).json({ error: `no cube ${JSON.stringify(id)}` });
			return;
		}
		const asked = Number.parseInt(String(req.query.n ?? '3'), 10);
		res.json({ arts: sampleArt(cards, Number.isFinite(asked) ? Math.min(Math.max(asked, 0), CUBE_ARTS_MAX) : 3) });
	});

	cubes.post('/import', (req: Request, res: Response) => {
		const parsed = ImportCubeBodySchema.safeParse(req.body);
		if (!parsed.success) return badRequest(res, 'body is { link }, or { name, list } with a name of 1 to 60 characters');
		if (!importLimit(req, res)) return;
		const caller = httpCaller(req);
		const body = parsed.data;
		const account = accountIdOf(req);
		('link' in body ? store.importLink(body.link, caller, account) : store.importList(body.name, body.list, caller, account))
			.then((summary) => checkAndSave(summary))
			.then((summary) => shown(req, [summary]))
			.then(([listing]) => res.status(201).json(listing))
			.catch((err: unknown) => {
				try {
					refusalStatus(res, err);
				} catch {
					warn({ evt: 'cube-import-failed', detail: (err as Error).message });
					badRequest(res, (err as Error).message);
				}
			});
	});

	cubes.post('/:id/refresh', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const caller = httpCaller(req);
		store
			.refresh(id, caller)
			.then((summary) => checkAndSave(summary))
			.then((summary) => shown(req, [summary]))
			.then(([listing]) => res.json(listing))
			.catch((err: unknown) => {
				try {
					refusalStatus(res, err);
				} catch {
					warn({ evt: 'cube-refresh-failed', id, detail: (err as Error).message });
					badRequest(res, (err as Error).message);
				}
			});
	});

	cubes.delete('/:id', (req: Request, res: Response) => {
		const id = String(req.params.id);
		const caller = httpCaller(req);
		try {
			store.remove(id, caller);
			res.status(204).end();
		} catch (err) {
			refusalStatus(res, err);
		}
	});

	api.use('/pools/cubes', cubes);
	api.use('/pools/cubes', bodyErrors());
}
