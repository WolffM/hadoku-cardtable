#!/usr/bin/env bash
#
# Wave 15, lane A -- the transport. This lane's OWN driver.
#
# The shared harness (../run.sh, ../index.html, ../serve.mjs, ../measure.mjs) is
# owned by nobody this wave and three lanes drive it concurrently, so this one
# brings its own copy of everything it needs and uses its own cache and port.
#
#   export SPIKE_CACHE=$HOME/.cache/w15a-transport
#   export PORT=8741
#
# Nothing here writes inside the repo, and nothing writes inside forge/ (D2).
# The vendored Forge checkout is READ, copied out, and patched in $SPIKE_CACHE.
#
# The toolchain is off $PATH on purpose (D14): Temurin JDK 21 under
# ~/.local/opt. `which javac` finding nothing is not a missing toolchain.
#
# Usage:
#   ./run.sh patch-check   apply the patch to a FRESH copy, dry run. exit 0 = clean
#   ./run.sh build         patch a fresh copy, compile, jar, stage the site
#   ./run.sh serve         foreground static + bridge server on $PORT
#   ./run.sh measure       headless Chromium at the page, print JSON to stdout
#   ./run.sh all           patch-check + build + measure
#
# Negative controls (each must turn exactly ONE check red):
#   W15A_MUTATE=nonce ./run.sh measure          -> nonce
#   W15A_MUTATE=same-defaults ./run.sh measure  -> distinctReplies
#   W15A_FAKE_BUILD_ID=stale ./run.sh measure   -> build

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SPIKE_CACHE="${SPIKE_CACHE:-$HOME/.cache/w15a-transport}"
WWW="$SPIKE_CACHE/www"
PORT="${PORT:-8741}"

# READ-ONLY source of Forge. The submodule is deliberately uninitialised in a
# worktree (wave trap 2), so the initialised MAIN checkout is the only copy --
# and it is never written to, never built in, and never `git submodule`-anything.
FORGE_SRC="${CARDTABLE_FORGE_SRC:-$HOME/repos/hadoku-cardtable/forge}"
FORGE_JAR="${CARDTABLE_FORGE_JAR:-$HOME/.local/share/cardtable/forge.jar}"
JDK_HOME="${JDK_HOME:-$(ls -d "$HOME"/.local/opt/jdk-21* 2>/dev/null | head -1)}"

# The one subtree the patch touches.
PKG_DIR="forge-gui/src/main/java/forge/gamemodes/net/client"

PW_CORE="${PW_CORE:-$(ls -d "$HOME"/repos/hadoku-cardtable/node_modules/.pnpm/playwright-core@*/node_modules/playwright-core 2>/dev/null | tail -1)}"

use_toolchain() {
    if [[ -z "$JDK_HOME" || ! -x "$JDK_HOME/bin/javac" ]]; then
        echo "no JDK at \$JDK_HOME=$JDK_HOME -- look in ~/.local/opt (D14)" >&2
        exit 1
    fi
    export JAVA_HOME="$JDK_HOME"
    export PATH="$JAVA_HOME/bin:$PATH"
}

# A FRESH copy of the pristine subtree, every time. "Reapplies cleanly" is only
# a claim if the thing it is applied to was never patched before.
fresh_copy() {
    local dest="$1"
    rm -rf "$dest"
    mkdir -p "$dest/$PKG_DIR"
    cp "$FORGE_SRC/$PKG_DIR"/*.java "$dest/$PKG_DIR/"
}

cmd_patch_check() {
    fresh_copy "$SPIKE_CACHE/patch-check"
    ( cd "$SPIKE_CACHE/patch-check" \
      && patch -p1 --dry-run --forward < "$HERE/forge-patch/0001-browser-transport.patch" )
}

cmd_build() {
    use_toolchain
    [[ -f "$FORGE_JAR" ]] || { echo "no Forge jar at $FORGE_JAR -- see docs/FORGE_JAR.md" >&2; exit 1; }
    [[ -d "$FORGE_SRC/$PKG_DIR" ]] || { echo "no Forge sources at $FORGE_SRC/$PKG_DIR" >&2; exit 1; }

    local work="$SPIKE_CACHE/work"
    fresh_copy "$work"
    ( cd "$work" && patch -p1 --forward < "$HERE/forge-patch/0001-browser-transport.patch" )

    # A build stamp compiled INTO the jar. This is the only way to tell "the
    # number did not change because nothing changed" from "the number did not
    # change because the old jar ran" -- that mistake has cost this repo a wave
    # (trap 7), and a jar mtime alone does not prove which CLASS answered.
    local build_id
    build_id="$(date -u +%Y%m%dT%H%M%SZ)-$(cat "$HERE/forge-patch/0001-browser-transport.patch" \
        "$HERE/java/spike/TransportProbe.java" | sha256sum | cut -c1-12)"
    mkdir -p "$SPIKE_CACHE/gen/spike"
    cat > "$SPIKE_CACHE/gen/spike/BuildId.java" <<EOF
package spike;
/** Generated by run.sh at build time. Do not edit; do not commit. */
public final class BuildId {
    public static final String ID = "$build_id";
    private BuildId() {}
}
EOF

    rm -rf "$SPIKE_CACHE/classes"
    mkdir -p "$SPIKE_CACHE/classes" "$WWW"

    # --release 17, not 21: CheerpJ 4.3 refuses class files above major 61, and
    # forge/pom.xml:27 builds at 17 anyway.
    javac --release 17 -nowarn -cp "$FORGE_JAR" -d "$SPIKE_CACHE/classes" \
        "$work/$PKG_DIR"/*.java \
        "$SPIKE_CACHE/gen/spike/BuildId.java" \
        "$HERE"/java/spike/*.java

    "$JAVA_HOME/bin/jar" --create --file "$WWW/transport.jar" -C "$SPIKE_CACHE/classes" .

    cp -f "$HERE/index.html" "$WWW/index.html"
    cp -f "$FORGE_JAR" "$WWW/forge.jar"
    printf '%s' "$build_id" > "$WWW/buildid.txt"

    echo "build id: $build_id"
    ls -l "$WWW"
    echo "class file major version of the patched FGameClient:"
    "$JAVA_HOME/bin/javap" -verbose -cp "$SPIKE_CACHE/classes" \
        forge.gamemodes.net.client.FGameClient | grep -E '^  (major|minor)'
    echo "the patched class really is in the jar, and really has the new method:"
    "$JAVA_HOME/bin/javap" -cp "$SPIKE_CACHE/classes" \
        forge.gamemodes.net.client.FGameClient | grep -F 'getBrowserTransport'
}

cmd_serve() {
    exec node "$HERE/serve.mjs" "$WWW" "$PORT"
}

cmd_measure() {
    [[ -f "$WWW/index.html" ]] || { echo "not staged -- run './run.sh build' first" >&2; exit 1; }
    [[ -n "$PW_CORE" && -d "$PW_CORE" ]] || { echo "no playwright-core (\$PW_CORE=$PW_CORE)" >&2; exit 1; }
    node "$HERE/serve.mjs" "$WWW" "$PORT" > "$SPIKE_CACHE/server.log" 2>&1 &
    local srv=$!
    trap 'kill '"$srv"' 2>/dev/null || true' EXIT
    for _ in $(seq 1 50); do
        if curl -fs -o /dev/null "http://127.0.0.1:$PORT/index.html"; then break; fi
        sleep 0.2
    done
    # $W15A_FAKE_BUILD_ID and $W15A_MUTATE are the negative controls; see the
    # header of measure.mjs and serve.mjs. Unset, they change nothing.
    PW_CORE="$PW_CORE" BUILD_ID="${W15A_FAKE_BUILD_ID:-$(cat "$WWW/buildid.txt")}" \
        node "$HERE/measure.mjs" "http://127.0.0.1:$PORT/index.html"
}

case "${1:-all}" in
    patch-check) cmd_patch_check ;;
    build)       cmd_build ;;
    serve)       cmd_serve ;;
    measure)     cmd_measure ;;
    all)         cmd_patch_check; cmd_build; cmd_measure ;;
    *) echo "unknown command: $1" >&2; exit 2 ;;
esac
