///usr/bin/env java --source 17
//
// Wave 1, lane B. Emits scripts/spike/teavm/src/main/java/spike/SpikePlayerController.java.
//
// forge.game.player.PlayerController has 110 abstract methods and the only
// concrete subclasses live in forge-ai and forge-gui, i.e. outside the two
// modules this spike is allowed to link. So the spike needs its own, and
// hand-writing 110 stubs is neither interesting nor reviewable.
//
// The generated stub throws on every decision point. That is deliberate: a
// scripted interaction that needs no player input must run without touching it,
// and if one does need input the stack trace names exactly which decision.
//
// Usage (see run.sh gen-controller):
//   java -cp <forge-core.jar:forge-game.jar:deps> scripts/spike/gen-controller-stub.java <outFile>

import java.io.IOException;
import java.io.PrintWriter;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Parameter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

public class GenControllerStub {
    public static void main(String[] args) throws Exception {
        Path out = Path.of(args[0]);
        Class<?> pc = Class.forName("forge.game.player.PlayerController");

        Set<String> seen = new LinkedHashSet<>();
        List<Method> abstracts = new ArrayList<>();
        for (Class<?> c = pc; c != null; c = c.getSuperclass()) {
            for (Method m : c.getDeclaredMethods()) {
                if (!Modifier.isAbstract(m.getModifiers())) {
                    continue;
                }
                String key = m.getName() + descriptor(m);
                if (seen.add(key)) {
                    abstracts.add(m);
                }
            }
        }
        abstracts.sort(Comparator.comparing(Method::getName).thenComparing(GenControllerStub::descriptor));

        Files.createDirectories(out.getParent());
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(out))) {
            w.println("package spike;");
            w.println();
            w.println("// GENERATED by scripts/spike/gen-controller-stub.java -- do not edit by hand.");
            w.println("// " + abstracts.size() + " abstract methods on forge.game.player.PlayerController.");
            w.println("//");
            w.println("// Every method throws. A scripted interaction that needs no player input");
            w.println("// never reaches one; if it does, the exception names the decision.");
            w.println("public class SpikePlayerController extends forge.game.player.PlayerController {");
            w.println("    public SpikePlayerController(forge.game.Game game, forge.game.player.Player player,");
            w.println("            forge.LobbyPlayer lobbyPlayer) {");
            w.println("        super(game, player, lobbyPlayer);");
            w.println("    }");
            w.println();
            w.println("    private static RuntimeException noInput(String method) {");
            w.println("        return new UnsupportedOperationException(");
            w.println("                \"SpikePlayerController: the engine asked for a decision: \" + method);");
            w.println("    }");
            for (Method m : abstracts) {
                w.println();
                w.println("    @Override");
                w.print("    public " + typeName(m.getGenericReturnType()) + " " + m.getName() + "(");
                Parameter[] ps = m.getParameters();
                for (int i = 0; i < ps.length; i++) {
                    if (i > 0) {
                        w.print(", ");
                    }
                    w.print(typeName(ps[i].getParameterizedType()) + " a" + i);
                }
                w.println(") {");
                w.println("        throw noInput(\"" + m.getName() + descriptor(m) + "\");");
                w.println("    }");
            }
            w.println("}");
        }
        System.out.println("wrote " + out + " (" + abstracts.size() + " methods)");
    }

    private static String descriptor(Method m) {
        StringBuilder sb = new StringBuilder("(");
        for (Class<?> p : m.getParameterTypes()) {
            sb.append(p.getSimpleName()).append(',');
        }
        return sb.append(')').toString();
    }

    // Erased types only: generic signatures would need bound handling that buys
    // nothing here, and @Override tolerates erasure.
    private static String typeName(java.lang.reflect.Type t) {
        if (t instanceof Class<?> c) {
            return c.isArray() ? typeName(c.getComponentType()) + "[]" : c.getCanonicalName();
        }
        if (t instanceof java.lang.reflect.ParameterizedType p) {
            return typeName(p.getRawType());
        }
        if (t instanceof java.lang.reflect.GenericArrayType g) {
            return typeName(g.getGenericComponentType()) + "[]";
        }
        if (t instanceof java.lang.reflect.TypeVariable<?> v) {
            java.lang.reflect.Type[] bounds = v.getBounds();
            return bounds.length > 0 ? typeName(bounds[0]) : "java.lang.Object";
        }
        if (t instanceof java.lang.reflect.WildcardType) {
            return "java.lang.Object";
        }
        throw new IllegalStateException("unhandled type " + t);
    }

    private GenControllerStub() throws IOException {
    }
}
