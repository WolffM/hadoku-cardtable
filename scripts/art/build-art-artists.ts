/*
 * Build `apps/ui/src/draft/art-artists.json` — the artist of every art id the
 * UI can show, for the places that show a card's art without its frame.
 *
 * ## Regenerate with
 *
 *   node scripts/art/build-art-artists.ts --cache=<any checkout>/packages/carddata/data
 *
 * after `build-art-ids.ts`, which decides which ids exist. `--cache` defaults to
 * `packages/carddata/data` (gitignored; a worktree has none of its own).
 *
 * ## Why this file exists
 *
 * A whole card face prints its illustrator and copyright, so a tile showing the
 * whole face needs no credit of its own. The stack's ability chip and the deck
 * chooser's tiles show only the art window, and Scryfall's image guidelines ask
 * that art shown that way carries its artist in the same interface. Forge's wire
 * carries no artist and neither does `art-ids.json`, so this is the table those
 * two places read it from. It is a separate file so it can be a lazy chunk: only
 * a credit needs it, and a credit can wait for it.
 *
 * Names are deduplicated into `names`, and `ids` maps an art id (a Scryfall id,
 * or `<id>#back` for a back face) to its index there. Ids only from the two
 * committed tables — no URL, no image metadata.
 */

import { createReadStream, readFileSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { join, resolve as resolvePath } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BACK_FACE } from '../../packages/carddata/src/art/ids.ts';

const REPO_ROOT = resolvePath(fileURLToPath(new URL('.', import.meta.url)), '..', '..');
const DRAFT_DIR = join(REPO_ROOT, 'apps', 'ui', 'src', 'draft');

interface Printing {
  readonly id: string;
  readonly artist?: string;
  readonly card_faces?: readonly { readonly artist?: string }[];
}

/** Every art id the UI resolves art for: `art-ids.json`'s rows and the cube pool's cards. */
function artIds(): Set<string> {
  const ids = new Set<string>();
  const table = JSON.parse(readFileSync(join(DRAFT_DIR, 'art-ids.json'), 'utf8')) as { ids: Record<string, string> };
  for (const id of Object.values(table.ids)) ids.add(id);
  const pool = JSON.parse(readFileSync(join(DRAFT_DIR, 'pool.json'), 'utf8')) as { cards: { scryfallId: string }[] };
  for (const card of pool.cards) ids.add(card.scryfallId);
  return ids;
}

/** A face's artist: its own when the faces were drawn by different hands, else the card's. */
function artistOf(printing: Printing, back: boolean): string | null {
  const face = printing.card_faces?.[back ? 1 : 0]?.artist;
  return face ?? printing.artist ?? null;
}

async function main(argv: readonly string[]): Promise<number> {
  let cacheDir = join(REPO_ROOT, 'packages', 'carddata', 'data');
  for (const arg of argv) {
    if (arg.startsWith('--cache=')) cacheDir = resolvePath(arg.slice('--cache='.length));
    else {
      console.error(`Unknown argument '${arg}'\nUsage: build-art-artists.ts [--cache=<dir>]`);
      return 2;
    }
  }

  const wanted = artIds();
  const fronts = new Set([...wanted].map((id) => (id.endsWith(BACK_FACE) ? id.slice(0, -BACK_FACE.length) : id)));
  const printings = new Map<string, Printing>();
  const lines = createInterface({ input: createReadStream(join(cacheDir, 'cards.jsonl'), { encoding: 'utf8' }), crlfDelay: Infinity });
  for await (const line of lines) {
    if (line.length === 0) continue;
    const printing = JSON.parse(line) as Printing;
    if (fronts.has(printing.id)) printings.set(printing.id, printing);
  }

  const byId = new Map<string, string>();
  const missing: string[] = [];
  for (const id of [...wanted].sort()) {
    const back = id.endsWith(BACK_FACE);
    const printing = printings.get(back ? id.slice(0, -BACK_FACE.length) : id);
    const artist = printing === undefined ? null : artistOf(printing, back);
    if (artist === null) missing.push(id);
    else byId.set(id, artist);
  }

  const names = [...new Set(byId.values())].sort();
  const index = new Map(names.map((name, i) => [name, i]));
  const rows = [...byId].map(([id, artist]) => `    ${JSON.stringify(id)}: ${index.get(artist)}`);
  const body = `{
  "version": 1,
  "note": ${JSON.stringify('GENERATED by scripts/art/build-art-artists.ts — do not edit by hand. The artist of every art id in art-ids.json and pool.json: ids maps an id to its index in names.')},
  "names": [
${names.map((name) => `    ${JSON.stringify(name)}`).join(',\n')}
  ],
  "ids": {
${rows.join(',\n')}
  }
}
`;
  const outFile = join(DRAFT_DIR, 'art-artists.json');
  writeFileSync(outFile, body, 'utf8');
  console.log(`Wrote ${byId.size} ids, ${names.length} artists (${Buffer.byteLength(body)} bytes) to ${outFile}`);
  if (missing.length > 0) console.log(`  ${missing.length} id(s) have no artist in the cache: ${missing.slice(0, 10).join(', ')}`);
  return 0;
}

process.exitCode = await main(process.argv.slice(2));
