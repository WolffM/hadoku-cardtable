/*
 * Build `apps/ui/src/draft/deck-art-traits.json` — what the deck chooser needs to
 * know about a library card to decide whether its art should stand for a deck.
 *
 * ## Regenerate with
 *
 *   node scripts/art/build-deck-art-traits.ts --cache=<any checkout>/packages/carddata/data
 *
 * after `build-art-ids.ts` or `build-deck-costs.ts`. `--cache` defaults to
 * `packages/carddata/data` (gitignored; a worktree has none of its own).
 *
 * ## Why this file exists
 *
 * `deckArtCandidates` in `ConstructedScreen.tsx` ranks a deck's cards by how well
 * they stand for it: a mythic, a legend, a creature or planeswalker, a four-of.
 * A drafted card carries its own `rarity` and `typeLine`; a library deck is a list
 * of names, and `LIBRARY_CARD_COSTS` gives only their costs. So this is the rest,
 * for the same names: one short string per card, `<rarity>[L][C][P]` — rarity's
 * first letter, then Legendary, Creature and Planeswalker when the front face is
 * one. The rarity is the printing whose art the chooser shows (the bare-name row
 * of `art-ids.json`), so the art and the reason it was picked agree.
 */

import { createReadStream, readFileSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { join, resolve as resolvePath } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BACK_FACE } from '../../packages/carddata/src/art/ids.ts';
import { LIBRARY_CARD_COSTS } from '../../packages/deck/src/library/deck-costs.generated.ts';

const REPO_ROOT = resolvePath(fileURLToPath(new URL('.', import.meta.url)), '..', '..');
const DRAFT_DIR = join(REPO_ROOT, 'apps', 'ui', 'src', 'draft');

interface Printing {
  readonly id: string;
  readonly rarity?: string;
  readonly type_line?: string;
  readonly card_faces?: readonly { readonly type_line?: string }[];
}

/** `<rarity>[L][C][P]` for one printing's front face. */
export function traitsOf(printing: Printing): string {
  const type = printing.card_faces?.[0]?.type_line ?? (printing.type_line ?? '').split(' // ')[0] ?? '';
  const words = new Set(type.split(/[\s—-]+/));
  return (
    (printing.rarity ?? 'common').charAt(0) +
    (words.has('Legendary') ? 'L' : '') +
    (words.has('Creature') ? 'C' : '') +
    (words.has('Planeswalker') ? 'P' : '')
  );
}

async function main(argv: readonly string[]): Promise<number> {
  let cacheDir = join(REPO_ROOT, 'packages', 'carddata', 'data');
  for (const arg of argv) {
    if (arg.startsWith('--cache=')) cacheDir = resolvePath(arg.slice('--cache='.length));
    else {
      console.error(`Unknown argument '${arg}'\nUsage: build-deck-art-traits.ts [--cache=<dir>]`);
      return 2;
    }
  }

  const table = JSON.parse(readFileSync(join(DRAFT_DIR, 'art-ids.json'), 'utf8')) as { ids: Record<string, string> };
  const idOf = new Map<string, string>();
  for (const name of Object.keys(LIBRARY_CARD_COSTS)) {
    const id = table.ids[name];
    if (id !== undefined) idOf.set(name, id.endsWith(BACK_FACE) ? id.slice(0, -BACK_FACE.length) : id);
  }
  const wanted = new Set(idOf.values());
  const printings = new Map<string, Printing>();
  const lines = createInterface({ input: createReadStream(join(cacheDir, 'cards.jsonl'), { encoding: 'utf8' }), crlfDelay: Infinity });
  for await (const line of lines) {
    if (line.length === 0) continue;
    const printing = JSON.parse(line) as Printing;
    if (wanted.has(printing.id)) printings.set(printing.id, printing);
  }

  const rows: string[] = [];
  const missing: string[] = [];
  for (const [name, id] of [...idOf].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const printing = printings.get(id);
    if (printing === undefined) missing.push(name);
    else rows.push(`    ${JSON.stringify(name)}: ${JSON.stringify(traitsOf(printing))}`);
  }
  const body = `{
  "version": 1,
  "note": ${JSON.stringify('GENERATED by scripts/art/build-deck-art-traits.ts — do not edit by hand. Every library card with a cost: <rarity>[L][C][P] for the printing art-ids.json shows (Legendary, Creature, Planeswalker front face).')},
  "traits": {
${rows.join(',\n')}
  }
}
`;
  const outFile = join(DRAFT_DIR, 'deck-art-traits.json');
  writeFileSync(outFile, body, 'utf8');
  console.log(`Wrote ${rows.length} cards (${Buffer.byteLength(body)} bytes) to ${outFile}`);
  if (missing.length > 0) console.log(`  ${missing.length} name(s) not in the cache: ${missing.slice(0, 10).join(', ')}`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
