/*
 * Freezes the play style the selection gave every LIBRARY deck — aggro,
 * midrange, control or combo — into `deck-styles.generated.ts`, so the deck
 * picker can tag a deck with it.
 *
 * Run from the repo root — no corpus, no network, so it runs in a worktree:
 *
 *   node packages/deck/src/library/build-deck-styles.ts
 *
 * ## Where the style comes from
 *
 * `docs/planning/deck-selection/tools/select_decks.py` classified every
 * candidate deck while choosing (`analyze.classify`, with the hand corrections
 * in `style-overrides*.json` already applied), and wrote the result as `style`
 * on each `chosen` entry of `selections/selection[-<family>]-<year>.json`. The
 * selection is the one place a style is decided; this script only joins it to
 * the catalogue.
 *
 * ## The join
 *
 * A library deck's `Source URL` is the mtgtop8 page it was transcribed from,
 * and its `d=` parameter is the selection entry's own `deck` id — the number,
 * not a filename derived from a player's name, so a renamed file cannot break
 * it. A catalogued deck whose id is in no `chosen` entry of its era's selection
 * is a throw: the library and the selection have drifted, which is a fact to
 * look at rather than a deck to leave untagged.
 *
 * ## A second copy, guarded the way the cost map is
 *
 * `deck-styles.test.ts` re-derives the map from the selections and the `.dck`
 * files on every run and compares it as text, so a new era catalogued without
 * a re-run is red rather than quiet.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { LIBRARY, deckPath, type FormatFamily, type LibraryCollection } from './catalog.ts';
import { loadLibraryDeck } from './library.ts';

/** `packages/deck/src/library` → the repo root. */
const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');

const read = (repoRelative: string): string => readFileSync(join(REPO_ROOT, repoRelative), 'utf8');

/** The four styles `select_decks.py` sorts decks into (`tools/analyze.py`'s `classify`). */
const DECK_STYLES = ['aggro', 'midrange', 'control', 'combo'] as const;

type DeckStyle = (typeof DECK_STYLES)[number];

const isDeckStyle = (s: unknown): s is DeckStyle => DECK_STYLES.includes(s as DeckStyle);

interface ChosenStyle {
  readonly deck: number;
  readonly style: unknown;
}

/** `select_decks.py`'s own file naming (`tools/eras.py`): Standard is bare, the others are prefixed. */
function selectionPath(family: FormatFamily, year: string): string {
  const name = family === 'standard' ? `selection-${year}.json` : `selection-${family}-${year}.json`;
  return `docs/planning/deck-selection/selections/${name}`;
}

/** The mtgtop8 deck id a library file was transcribed from — its `Source URL`'s `d=`. */
function mtgtop8DeckId(collection: LibraryCollection, file: string, sourceUrl: string): number {
  const id = new URL(sourceUrl).searchParams.get('d');
  if (id === null || !/^\d+$/.test(id)) {
    throw new Error(`${collection.id}/${file}: Source URL ${sourceUrl} names no mtgtop8 deck id`);
  }
  return Number(id);
}

/** Catalogue entry id → the style its era's selection gave it, in catalogue order. */
export function libraryDeckStyles(): Record<string, DeckStyle> {
  const styles: Record<string, DeckStyle> = {};
  for (const collection of LIBRARY) {
    const path = selectionPath(collection.family, collection.date.slice(0, 4));
    const chosen = (JSON.parse(read(path)) as { chosen: readonly ChosenStyle[] }).chosen;
    const byDeck = new Map(chosen.map((c) => [c.deck, c.style]));
    for (const entry of collection.decks) {
      const deck = loadLibraryDeck(read(deckPath(collection, entry)));
      const id = mtgtop8DeckId(collection, entry.file, deck.citation);
      const style = byDeck.get(id);
      if (!isDeckStyle(style)) {
        throw new Error(`${entry.id}: mtgtop8 deck ${String(id)} has no style in ${path} (got ${String(style)})`);
      }
      if (styles[entry.id] !== undefined) throw new Error(`${entry.id}: catalogued twice`);
      styles[entry.id] = style;
    }
  }
  return styles;
}

/** The module text, so the test can compare text and not only values. */
export function deckStylesModule(styles: Readonly<Record<string, DeckStyle>>): string {
  const entries = Object.entries(styles)
    .map(([id, style]) => `  ${JSON.stringify(id)}: ${JSON.stringify(style)},`)
    .join('\n');
  return `/*
 * GENERATED by packages/deck/src/library/build-deck-styles.ts. Do not hand-edit
 * — regenerate:
 *
 *   node packages/deck/src/library/build-deck-styles.ts
 *
 * The play style \`select_decks.py\` gave each of the ${String(Object.keys(styles).length)} catalogued library decks,
 * keyed by catalogue entry id, read from \`docs/planning/deck-selection/selections/\`.
 *
 * \`deck-styles.test.ts\` re-derives this from the selections and the \`.dck\`
 * files on every run, so a stale copy is red rather than quiet.
 */

/** How a deck means to win, as the selection classified it. */
export type DeckStyle = ${DECK_STYLES.map((s) => `'${s}'`).join(' | ')};

export const LIBRARY_DECK_STYLES: Readonly<Record<string, DeckStyle>> = {
${entries}
};
`;
}

function main(): void {
  const styles = libraryDeckStyles();
  const target = join(dirname(fileURLToPath(import.meta.url)), 'deck-styles.generated.ts');
  writeFileSync(target, deckStylesModule(styles), 'utf8');
  console.log(`deck-styles.generated.ts: ${String(Object.keys(styles).length)} decks`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
